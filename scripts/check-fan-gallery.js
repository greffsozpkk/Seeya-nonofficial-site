const assert=require('node:assert/strict');
const {prepare,pageSlice,cards,pagination}=require('../src/shared/fan-gallery');
const data=require('../src/data/fan-posts.json');
const posts=prepare(data);assert.equal(posts.length,data.posts.length);assert(posts.length>0);
const fixture=Array.from({length:13},(_,i)=>({...posts[0],id:'sample'+i}));
assert.equal(pageSlice(fixture,1).items.length,6);
assert.equal(pageSlice(fixture,2).items.length,6);
assert.equal(pageSlice(fixture,3).items.length,1);
assert.equal(new Set([1,2,3].flatMap(n=>pageSlice(fixture,n).items.map(p=>p.id))).size,13);
for(const invalid of [null,'invalid',0,-1,1.5,Infinity])assert.equal(pageSlice(fixture,invalid).page,1);
assert.equal(pageSlice(fixture,999).page,3);
assert.equal(pageSlice([],3).page,1);
assert.equal(pagination(1,1),'');
assert.throws(()=>prepare({...data,posts:[...data.posts,data.posts[0]]}));
assert.throws(()=>prepare({...data,posts:[{...data.posts[0],account:'bad" onclick="'}]}));
assert.throws(()=>prepare({...data,posts:[{...data.posts[0],id:'../invalid'}]}));
assert.throws(()=>prepare({...data,posts:[{...data.posts[0],kind:'../'}]}));
const reel=cards([{...posts[0],kind:'reel'}]);
assert(reel.includes('data-instgrm-permalink="https://www.instagram.com/reel/'+posts[0].id+'/"'));
assert(cards([{...posts[0],kind:undefined}]).includes('data-instgrm-permalink="https://www.instagram.com/p/'+posts[0].id+'/"'));
const unsafe=cards([{...posts[0],label:'<img src=x onerror=alert(1)>',accountName:'<script>'}]);
assert(!unsafe.includes('<img src=x'));assert(unsafe.includes('&lt;script&gt;'));
console.log('PASS: fan gallery pagination, URL bounds, unique posts, account validation, HTML escaping.');
